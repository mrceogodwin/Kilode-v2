function track(partial: Omit<MusicTrack, "embed" | "platform" | "url"> & { url: string }): MusicTrack {
  const parsed = parseMusicUrl(partial.url);
  return {
    ...partial,
    url: parsed?.url ?? partial.url,
    platform: parsed?.platform ?? "Link",
    embed: parsed?.embed,
  };
}

