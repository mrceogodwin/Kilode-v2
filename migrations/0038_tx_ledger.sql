CREATE TABLE IF NOT EXISTS nf_tx (
  hash TEXT PRIMARY KEY,
  kind TEXT NOT NULL,
  ref_id TEXT NOT NULL,
  user_id TEXT NOT NULL,
  coin TEXT NOT NULL DEFAULT '',
  amount TEXT NOT NULL DEFAULT '',
  ts BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS nf_events (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  blurb TEXT NOT NULL DEFAULT '',
  category TEXT NOT NULL DEFAULT 'culture',
  place TEXT NOT NULL DEFAULT '',
  link TEXT NOT NULL DEFAULT '',
  cover TEXT NOT NULL DEFAULT '',
  starts_at BIGINT NOT NULL,
  ends_at BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  flagship INTEGER NOT NULL DEFAULT 0,
  submitter TEXT NOT NULL DEFAULT '',
  user_id TEXT,
  ts BIGINT NOT NULL
);

ALTER TABLE nf_events ADD COLUMN IF NOT EXISTS coin TEXT NOT NULL DEFAULT '';
ALTER TABLE nf_events ADD COLUMN IF NOT EXISTS amount TEXT NOT NULL DEFAULT '';
ALTER TABLE nf_events ADD COLUMN IF NOT EXISTS tx_hash TEXT NOT NULL DEFAULT '';
ALTER TABLE nf_events ADD COLUMN IF NOT EXISTS match_note TEXT NOT NULL DEFAULT '';
